/* -------------------------------------------------------------------------
 * Internal helpers
 * ------------------------------------------------------------------------- */

static void write_cmd_seq(SSD1306_Handle *h, const uint8_t *cmds, size_t len)
{
    /* SSD1306 I2C command packet: [0x00, cmd0, cmd1, ...] */
    uint8_t buf[32];
    buf[0] = 0x00;
    for (size_t i = 0; i < len && i < sizeof(buf) - 1; i++)
        buf[i + 1] = cmds[i];
    hal_i2c_write(h->i2c, h->addr, buf, len + 1);
}

/* -------------------------------------------------------------------------
 * ssd1306_init
 * ------------------------------------------------------------------------- */

void ssd1306_init(SSD1306_Handle *h, HAL_I2C_Handle *i2c, uint8_t addr)
{
    h->i2c  = i2c;
    h->addr = addr;
    memset(h->fb, 0, sizeof(h->fb));

    static const uint8_t init_seq[] = {
        0xAE,       /* display off                         */
        0xD5, 0x80, /* clock divide ratio / osc freq       */
        0xA8, 0x3F, /* multiplex ratio = 63 (64 rows)      */
        0xD3, 0x00, /* display offset = 0                  */
        0x40,       /* start line = 0                      */
        0x8D, 0x14, /* charge pump on (3.3 V module)       */
        0x20, 0x00, /* horizontal addressing mode          */
        0xA1,       /* segment remap: col 127 → SEG0       */
        0xC8,       /* COM scan: remapped (top → bottom)   */
        0xDA, 0x12, /* COM pins: alternative config        */
        0x81, 0xCF, /* contrast                            */
        0xD9, 0xF1, /* pre-charge period                   */
        0xDB, 0x40, /* VCOMH deselect level                */
        0xA4,       /* follow RAM (not force-on)           */
        0xA6,       /* normal display (not inverted)       */
        0xAF,       /* display on                          */
    };
    write_cmd_seq(h, init_seq, sizeof(init_seq));
}

/* -------------------------------------------------------------------------
 * ssd1306_clear
 * ------------------------------------------------------------------------- */

void ssd1306_clear(SSD1306_Handle *h)
{
    memset(h->fb, 0, sizeof(h->fb));
}

/* -------------------------------------------------------------------------
 * ssd1306_flush
 *
 * Sends all 8 pages (1024 bytes) to the display using horizontal addressing.
 * Each page is transmitted as a separate I2C transaction to keep the buffer
 * size small (129 bytes: 1 control byte + 128 data bytes).
 * ------------------------------------------------------------------------- */

void ssd1306_flush(SSD1306_Handle *h)
{
    /* Reset column and page pointers back to (0, 0) */
    static const uint8_t addr_reset[] = {
        0x21, 0x00, 0x7F, /* column address 0..127 */
        0x22, 0x00, 0x07, /* page address   0..7   */
    };
    write_cmd_seq(h, addr_reset, sizeof(addr_reset));

    /* Send one page at a time: control byte 0x40 = data follows */
    uint8_t buf[SSD1306_WIDTH + 1];
    buf[0] = 0x40;
    for (uint8_t page = 0; page < SSD1306_PAGES; page++) {
        memcpy(&buf[1], h->fb[page], SSD1306_WIDTH);
        hal_i2c_write(h->i2c, h->addr, buf, sizeof(buf));
    }
}

/* -------------------------------------------------------------------------
 * ssd1306_draw_pixel
 * ------------------------------------------------------------------------- */

void ssd1306_draw_pixel(SSD1306_Handle *h, uint8_t x, uint8_t y, bool on)
{
    if (x >= SSD1306_WIDTH || y >= SSD1306_HEIGHT) return;
    if (on)
        h->fb[y / 8][x] |=  (uint8_t)(1u << (y % 8));
    else
        h->fb[y / 8][x] &= ~(uint8_t)(1u << (y % 8));
}

/* -------------------------------------------------------------------------
 * ssd1306_draw_char
 * ------------------------------------------------------------------------- */

void ssd1306_draw_char(SSD1306_Handle *h, uint8_t x, uint8_t page, char c)
{
    if ((uint8_t)c < 0x20 || (uint8_t)c > 0x7E) c = '?';
    const uint8_t *glyph = font5x8[(uint8_t)c - 0x20];
    for (uint8_t col = 0; col < 5; col++) {
        if (x + col < SSD1306_WIDTH)
            h->fb[page][x + col] = glyph[col];
    }
    /* 6th column is a blank spacer — already 0 from ssd1306_clear */
}

/* -------------------------------------------------------------------------
 * ssd1306_draw_string
 * ------------------------------------------------------------------------- */

void ssd1306_draw_string(SSD1306_Handle *h, uint8_t x, uint8_t page, const char *s)
{
    while (*s && x + 5 <= SSD1306_WIDTH) {
        ssd1306_draw_char(h, x, page, *s++);
        x += 6; /* 5-pixel glyph + 1-pixel spacer */
    }
}
